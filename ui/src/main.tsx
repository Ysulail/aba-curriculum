import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import '@aws-amplify/ui-react/styles.css'
import './index.css'
import App from './App'
import { loadConfig } from './config'
import { configureAuth } from './amplify-config'

const root = createRoot(document.getElementById('root')!)
loadConfig().then((config) => {
  configureAuth(config)
  root.render(<StrictMode><App config={config} /></StrictMode>)
}).catch((error: unknown) => {
  root.render(<main className="setup-error"><p className="eyebrow">HR LEAVE PORTAL</p><h1>Portal setup needed</h1><p role="alert">{error instanceof Error ? error.message : 'Unable to initialize portal.'}</p><p>Provide the public runtime configuration generated by the UI CDK stack, then reload.</p></main>)
})
